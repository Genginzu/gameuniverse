-- Migration: Unify group roles to owner / moderator / member
-- Groups previously used owner/admin/member; communities already use
-- owner/moderator/member. This aligns groups onto the same 3-level hierarchy
-- (admin = owner = creator, moderators, members) and renames the helper
-- function is_group_owner_or_admin -> is_group_owner_or_moderator.

-- =============================================================================
-- 1. Migrate existing data + swap the CHECK constraint
-- =============================================================================

-- Drop the old CHECK constraint (name auto-generated by Postgres for inline
-- CHECK on column role). We drop by locating it dynamically to be safe.
DO $$
DECLARE
  constraint_name TEXT;
BEGIN
  SELECT con.conname INTO constraint_name
  FROM pg_constraint con
  JOIN pg_class rel ON rel.oid = con.conrelid
  JOIN pg_namespace nsp ON nsp.oid = rel.relnamespace
  WHERE nsp.nspname = 'public'
    AND rel.relname = 'group_members'
    AND con.contype = 'c'
    AND pg_get_constraintdef(con.oid) ILIKE '%role%';

  IF constraint_name IS NOT NULL THEN
    EXECUTE format('ALTER TABLE public.group_members DROP CONSTRAINT %I', constraint_name);
  END IF;
END $$;

-- Migrate existing 'admin' rows to 'moderator'
UPDATE public.group_members SET role = 'moderator' WHERE role = 'admin';

-- Add the new CHECK constraint
ALTER TABLE public.group_members
  ADD CONSTRAINT group_members_role_check CHECK (role IN ('owner', 'moderator', 'member'));

COMMENT ON COLUMN public.group_members.role IS 'owner: creator, full control; moderator: can moderate; member: regular member';

-- =============================================================================
-- 2. Rename helper function is_group_owner_or_admin -> is_group_owner_or_moderator
-- =============================================================================

CREATE OR REPLACE FUNCTION public.is_group_owner_or_moderator(p_group_id UUID, p_player_id UUID)
RETURNS BOOLEAN
LANGUAGE sql
SECURITY DEFINER
STABLE
SET search_path = public
AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.group_members
    WHERE group_id = p_group_id AND player_id = p_player_id AND role IN ('owner', 'moderator')
  );
$$;

-- =============================================================================
-- 3. Recreate the policies that referenced is_group_owner_or_admin
-- =============================================================================

DROP POLICY IF EXISTS "Owners and admins can update their group" ON public.groups;
CREATE POLICY "Owners and moderators can update their group"
  ON public.groups FOR UPDATE
  USING (public.is_group_owner_or_moderator(id, auth.uid()));

DROP POLICY IF EXISTS "Owners and admins can update member roles" ON public.group_members;
CREATE POLICY "Owners and moderators can update member roles"
  ON public.group_members FOR UPDATE
  USING (public.is_group_owner_or_moderator(group_id, auth.uid()));

DROP POLICY IF EXISTS "Members can leave, owners and admins can remove members" ON public.group_members;
CREATE POLICY "Members can leave, owners and moderators can remove members"
  ON public.group_members FOR DELETE
  USING (
    player_id = auth.uid()
    OR public.is_group_owner_or_moderator(group_id, auth.uid())
  );

DROP POLICY IF EXISTS "Authors can delete own posts, owners and admins can moderate" ON public.group_posts;
CREATE POLICY "Authors can delete own posts, owners and moderators can moderate"
  ON public.group_posts FOR DELETE
  USING (
    author_id = auth.uid()
    OR public.is_group_owner_or_moderator(group_id, auth.uid())
  );

-- group_invitations policies also referenced the old function
DROP POLICY IF EXISTS "Owners and admins can view group invitations" ON public.group_invitations;
CREATE POLICY "Owners and moderators can view group invitations"
  ON public.group_invitations FOR SELECT
  USING (public.is_group_owner_or_moderator(group_id, auth.uid()));

DROP POLICY IF EXISTS "Owners and admins can create group invitations" ON public.group_invitations;
CREATE POLICY "Owners and moderators can create group invitations"
  ON public.group_invitations FOR INSERT
  WITH CHECK (
    invited_by = auth.uid()
    AND public.is_group_owner_or_moderator(group_id, auth.uid())
  );

DROP POLICY IF EXISTS "Owners and admins can delete group invitations" ON public.group_invitations;
CREATE POLICY "Owners and moderators can delete group invitations"
  ON public.group_invitations FOR DELETE
  USING (public.is_group_owner_or_moderator(group_id, auth.uid()));

-- =============================================================================
-- 4. Drop the old helper function
-- =============================================================================

DROP FUNCTION IF EXISTS public.is_group_owner_or_admin(UUID, UUID);
